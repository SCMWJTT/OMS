def sheet(title, rows, cols, widths=None, numeric=(), freeze="B2", note=None):
    ws = wb.create_sheet(title)
    start = 1
    if note:
        ws.cell(1, 1, note).font = S; start = 3
    for j, c in enumerate(cols, 1):
        x = ws.cell(start, j, c); x.font = H; x.fill = HF; x.alignment = Alignment(vertical="center", wrap_text=True)
    for i, r in enumerate(rows, start + 1):
        for j, c in enumerate(cols, 1):
            v = r.get(c, "")
            if c in numeric and v not in ("", None):
                try: v = float(v) if "." in str(v) else int(v)
                except ValueError: pass
            x = ws.cell(i, j, v); x.font = B
    for j, c in enumerate(cols, 1):
        ws.column_dimensions[L(j)].width = (widths or {}).get(c, min(48, max(10, len(c) + 2)))
    ws.freeze_panes = ws.cell(start + 1, 2)
    ws.auto_filter.ref = f"A{start}:{L(len(cols))}{start + len(rows)}"
    return ws, start

